"""Generates EVENTS.md: which service publishes which integration event and who consumes it (F-05).

Scans the eduplatform-* repos next to this one, so the overview cannot go stale by hand:
  publisher = a repo that creates the event:   new XyzIntegrationEvent(
  consumer  = a class implementing             IConsumer<XyzIntegrationEvent>

Usage (from the folder that contains all eduplatform-* repos, or pass it as argument):
  python eduplatform-shared-kernel/tools/generate_events_md.py            # write EVENTS.md
  python eduplatform-shared-kernel/tools/generate_events_md.py --check    # exit 1 if an event has
                                                                          # consumers but no publisher
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KERNEL = os.path.dirname(HERE)
SKIP_DIRS = {"bin", "obj", ".git", "node_modules", "tests"}

EVENT_DEF = re.compile(r"public\s+(?:sealed\s+)?record\s+(\w+IntegrationEvent)\b")
NEW_EVENT = re.compile(r"\bnew\s+(?:\w+\.)*(\w+IntegrationEvent)\s*[({]")  # also new EduPlatform.SharedKernel.Events.X(
CLASS_DECL = re.compile(r"\bclass\s+(\w+)")
CONSUMES = re.compile(r"IConsumer<\s*([\w.]+)\s*>")


def service_name(repo):
    name = repo.removeprefix("eduplatform-")
    return name.removesuffix("-service")


def cs_files(root):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.endswith(".Tests")]
        for f in filenames:
            if f.endswith(".cs"):
                yield os.path.join(dirpath, f)


def read(path):
    with open(path, encoding="utf-8-sig", errors="replace") as f:
        return f.read()


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    check = "--check" in sys.argv
    root = os.path.abspath(args[0]) if args else os.path.dirname(KERNEL)

    # events defined in the SharedKernel (the only allowed place, F-05 step 2)
    events = {}
    for path in cs_files(os.path.join(KERNEL, "Events")):
        for name in EVENT_DEF.findall(read(path)):
            events[name] = {"publishers": set(), "consumers": set()}

    local_consumers = []  # IConsumer<T> where T is not a SharedKernel event (local copies, email contracts)
    repos = sorted(d for d in os.listdir(root)
                   if d.startswith("eduplatform-") and os.path.isdir(os.path.join(root, d))
                   and os.path.abspath(os.path.join(root, d)) != KERNEL)

    for repo in repos:
        svc = service_name(repo)
        for path in cs_files(os.path.join(root, repo)):
            src = read(path)
            for name in NEW_EVENT.findall(src):
                if name in events:
                    events[name]["publishers"].add(svc)
            classes = [(m.start(), m.group(1)) for m in CLASS_DECL.finditer(src)]
            for m in CONSUMES.finditer(src):
                # the consumer is the last class declared before "IConsumer<...>" (files can hold several)
                owners = [c for pos, c in classes if pos < m.start()]
                cls_name = owners[-1] if owners else os.path.basename(path)[:-3]
                full = m.group(1)
                name = full.split(".")[-1]
                if name in events:
                    events[name]["consumers"].add(f"{svc} ({cls_name})")
                else:
                    local_consumers.append((svc, cls_name, full))

    no_publisher = sorted(n for n, e in events.items() if e["consumers"] and not e["publishers"])
    no_consumer = sorted(n for n, e in events.items() if e["publishers"] and not e["consumers"])
    unused = sorted(n for n, e in events.items() if not e["publishers"] and not e["consumers"])

    lines = [
        "# Integration events",
        "",
        "Generated by `tools/generate_events_md.py` - do not edit by hand, run the script again",
        "after adding or changing an event, publisher or consumer.",
        "",
        "All events live in `Events/IntegrationEvents.cs` (SharedKernel). MassTransit routes by the full",
        "type name, so a local copy of an event class in a service never receives anything.",
        "",
        "| Event | Publisher | Consumer |",
        "|---|---|---|",
    ]
    for name in sorted(events):
        e = events[name]
        pub = ", ".join(sorted(e["publishers"])) or "**-**"
        con = "<br>".join(sorted(e["consumers"])) or "-"
        lines.append(f"| `{name.removesuffix('IntegrationEvent')}` | {pub} | {con} |")

    lines += ["", "## Checks", ""]
    lines.append("**Consumer without publisher** (waits for something nobody sends - the F-05 bug):")
    lines += [f"- `{n}`" for n in no_publisher] or ["- none"]
    lines += ["", "**Published, but nobody listens** (fine if meant for later, otherwise remove):"]
    lines += [f"- `{n}`" for n in no_consumer] or ["- none"]
    lines += ["", "**Defined, but neither published nor consumed:**"]
    lines += [f"- `{n}`" for n in unused] or ["- none"]
    lines += ["", "**Consumers of events that are not in the SharedKernel:**"]
    lines += [f"- {svc}: `{cls}` consumes `{t}`" for svc, cls, t in sorted(set(local_consumers))] or ["- none"]
    lines.append("")

    out = os.path.join(KERNEL, "EVENTS.md")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}: {len(events)} events, {len(no_publisher)} without publisher, "
          f"{len(no_consumer)} without consumer, {len(unused)} unused")

    if check and no_publisher:
        print("ERROR: consumers without publisher: " + ", ".join(no_publisher))
        sys.exit(1)


if __name__ == "__main__":
    main()
